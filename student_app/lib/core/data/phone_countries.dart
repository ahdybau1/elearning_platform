List<PhoneCountry> phoneCountriesSorted() => [
  ...kPhoneCountries.where((c) => kPriorityPhoneCountries.contains(c.code)),
  ...kPhoneCountries.where((c) => !kPriorityPhoneCountries.contains(c.code)),
];

PhoneCountry phoneCountryByCode(String? code) =>
    kPhoneCountries.firstWhere((c) => c.code == code, orElse: () => kPhoneCountries.firstWhere((c) => c.code == 'CM'));
